import { test, expect } from "@playwright/test";
import { randomUUID } from "node:crypto";
import AxeBuilder from "@axe-core/playwright";
for (const width of [1440, 375]) test(`Capture and develop an idea, archive and restore it at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 1000 });
  const headers = { origin: "http://127.0.0.1:3100" };
  const response = await page.request.post("/api/auth/signup", { headers, data: { name: "Idea researcher", email: `ideas-${randomUUID()}@example.test`, password: "Research123" } });
  expect(response.status()).toBe(201);
  await page.goto("/");
  await page.getByRole("button", { name: "Add item", exact: true }).first().click();
  const form = page.getByRole("dialog");
  await form.getByLabel("Type", { exact: true }).selectOption("idea");
  await expect(form.getByLabel("Link", { exact: true })).toHaveCount(0);
  await form.getByLabel("Title", { exact: true }).fill("A calmer reading workflow");
  await form.getByLabel("Content", { exact: true }).fill("## Research direction\n\n- Keep useful sources\n- Read later\n\n```ts\nconst useful = true;\n```\n\n<script>window.injected = true</script>\n\n![tracking](https://example.test/tracker.png)");
  await form.getByLabel("Why it matters").fill("Develop this before the next project.");
  await form.getByRole("button", { name: "Save item", exact: true }).click();
  await page.getByRole("link", { name: "A calmer reading workflow", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Research direction", exact: true })).toBeVisible();
  await expect(page.locator("pre code")).toHaveText("const useful = true;\n");
  expect(await page.evaluate(() => (window as any).injected)).toBeUndefined();
  await expect(page.locator('.item-markdown img')).toHaveCount(0);
  await expect(page.getByRole("link", { name: "Open source", exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "Favourite", exact: true }).click();
  await expect(page.getByRole("button", { name: "Favourited", exact: true })).toHaveAttribute("aria-pressed", "true");
  await page.getByRole("button", { name: "Edit", exact: true }).click();
  await page.getByLabel("Content", { exact: true }).fill("## Developed idea\n\nNew research with more context.");
  await page.getByRole("button", { name: "Save changes", exact: true }).click();
  await page.reload();
  await expect(page.getByRole("heading", { name: "Developed idea" })).toBeVisible();
  expect((await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze()).violations).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: `docs/evidence/library-v2/idea-${width}.png`, fullPage: true });
  await page.getByText("More", { exact: true }).click();
  await page.getByRole("button", { name: "Archive", exact: true }).click();
  await expect(page.getByText("Archived", { exact: true })).toBeVisible();
  await page.getByRole("link", { name: "Back to library" }).click();
  await expect(page.getByRole("link", { name: "A calmer reading workflow", exact: true })).toHaveCount(0);
  await page.getByRole("link", { name: "Archive", exact: true }).click();
  await page.getByRole("link", { name: "A calmer reading workflow", exact: true }).click();
  await page.getByText("More", { exact: true }).click();
  await page.getByRole("button", { name: "Move to Trash", exact: true }).click();
  await page.getByRole("link", { name: "Trash", exact: true }).click();
  const card = page.locator("article").filter({ hasText: "A calmer reading workflow" });
  await expect(card).toBeVisible();
  await card.getByRole("button", { name: "Restore", exact: true }).click();
  await expect(card).toHaveCount(0);
  await page.getByRole("link", { name: "Archive", exact: true }).click();
  await page.getByRole("link", { name: "A calmer reading workflow", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Developed idea" })).toBeVisible();
});
