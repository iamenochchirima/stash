test("Admin unavailable-server message can be retried without exposing credentials",async({page})=>{
  await page.route("**/admin-api/me",route=>route.fulfill({status:503,contentType:"application/json",body:JSON.stringify({error:"The server is unavailable. Please try again."})}));
  await page.goto(origin);
  await expect(page.getByRole("alert").filter({hasText:"The server is unavailable"})).toBeVisible();
  await page.unroute("**/admin-api/me");
  await page.getByRole("button",{name:"Retry connection",exact:true}).click();
  await expect(page.getByRole("heading",{name:"Sign in to Stash Admin"})).toBeVisible();
});
