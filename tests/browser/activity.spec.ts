import { test, expect } from "@playwright/test";
import { randomUUID } from "node:crypto";
import AxeBuilder from "@axe-core/playwright";

for (const width of [1440,375]) test(`Latest activity and live updated labels at ${width}px`, async ({page}) => {
  await page.setViewportSize({width,height:1000});
  const headers={origin:"http://127.0.0.1:3100"};
  const signup=await page.request.post("/api/auth/signup",{headers,data:{name:"Activity reader",email:`activity-${randomUUID()}@example.test`,password:"Research123"}});
  expect(signup.status()).toBe(201);
  const create=async(name:string)=>(await page.request.post("/api/projects",{headers,data:{name}})).json();
  const older=(await create("Older research")).project;
  await create("Newer research");
  const first=(await (await page.request.post("/api/items",{headers,data:{kind:"note",title:"First finding",body:"Early research",projectId:older.id}})).json()).item;
  await (await page.request.post("/api/items",{headers,data:{kind:"note",title:"Second finding",body:"Later research",projectId:older.id}})).json();
  const edited=await page.request.patch(`/api/items/${first.id}`,{headers,data:{revision:1,body:"Revised research"}});
  expect(edited.status()).toBe(200);
  const updatedAt=(await edited.json()).item.updatedAt;
  await page.clock.install();
  await page.goto("/projects");
  await expect(page.locator(".project-card").first()).toContainText("Older research");
  await expect(page.locator(".project-card").first().locator("time")).toContainText(/Updated \d+ sec ago/);
  await page.locator(".project-card").first().click();
  await expect(page.locator(".project-item").first()).toContainText("First finding");
  const stamp=page.locator(".project-item").first().locator("time");
  await expect(stamp).toHaveAttribute("datetime",updatedAt);
  await expect(stamp).toContainText(/Updated \d+ sec ago/);
  const previous=await stamp.innerText();
  await expect.poll(()=>stamp.innerText()).not.toBe(previous);
  const timestamp=Date.parse(updatedAt);
  await page.clock.setSystemTime(new Date(timestamp+5000));
  await page.clock.runFor(1000);
  await expect(stamp).toContainText(/Updated [56] sec ago/);
  await page.clock.setSystemTime(new Date(timestamp+30*86400000));
  await page.clock.runFor(1000);
  await expect(stamp).toHaveText("Updated 30 days ago");
  await page.clock.setSystemTime(new Date(timestamp+31*86400000));
  await page.clock.runFor(1000);
  await expect(stamp).not.toContainText("ago");
  await page.clock.setSystemTime(new Date());
  await page.clock.runFor(1000);
  await page.screenshot({path:`docs/evidence/browser/activity-items-${width}.png`,fullPage:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  expect((await new AxeBuilder({page}).withTags(["wcag2a","wcag2aa","wcag21aa"]).analyze()).violations).toEqual([]);
  await page.goto("/projects");
  await expect(page.locator(".project-card")).toHaveCount(2);
  await expect(page.locator(".project-card").first().locator("time")).toContainText("Updated");
  expect((await new AxeBuilder({page}).withTags(["wcag2a","wcag2aa","wcag21aa"]).analyze()).violations).toEqual([]);
  await page.screenshot({path:`docs/evidence/browser/activity-projects-${width}.png`,fullPage:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.goto(`/items/${first.id}`);
  await expect(page.locator(".item-meta time")).toContainText(/Updated/);
  await (await page.request.post("/api/items",{headers,data:{kind:"idea",title:"Library idea",body:"Useful thought"}})).json();
  await page.goto("/library");
  await expect(page.locator(".resource-card time")).toContainText(/Updated \d+ sec ago/);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
