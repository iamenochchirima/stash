import { test, expect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import { randomUUID } from "node:crypto";
import { mkdir } from "node:fs/promises";
for (const width of [1440, 375]) {
  test(`Open a private saved item from its card at ${width}px`, async ({ page, browser }) => {
    await page.setViewportSize({ width, height: 1000 });
    const email = `detail-${randomUUID()}@example.test`, password = "Detail123";
    const headers = { origin: "http://127.0.0.1:3100" };
    const signup = await page.request.post("/api/auth/signup", { headers, data: { email, password, name: "Item researcher" } });
    expect(signup.status()).toBe(201);
    const saved = await page.request.post("/api/resources", { headers, data: { url: "https://example.test/full-context", title: "A useful find", notes: "Full context that deserves its own reading page.\nA second paragraph retained exactly.", tags: ["research"] } });
    expect(saved.ok()).toBe(true);
    const id = (await saved.json()).item.id;
    await page.goto("/");
    await page.getByLabel("Search your library").fill("useful");
    const card = page.locator(".resource-card").filter({ hasText: "A useful find" });
    await expect(card).toBeVisible();
    const bounds = await card.boundingBox();
    await page.mouse.click(bounds!.x + 8, bounds!.y + 8);
    await expect(page).toHaveURL(new RegExp(`/items/${id}`));
    await expect(page.getByRole("heading", { name: "A useful find" })).toBeVisible();
    await expect(page.getByText("A second paragraph retained exactly.", { exact: false })).toBeVisible();
    await expect(page.getByRole("link", { name: "Open source", exact: true })).toHaveAttribute("href", "https://example.test/full-context");
    await page.reload();
    await expect(page.getByRole("heading", { name: "A useful find" })).toBeVisible();
    await page.getByRole("button", { name: "Edit", exact: true }).click();
    await page.getByLabel("Why it matters").fill("Updated context from the detail page.");
    await page.getByRole("button", { name: "Save changes" }).click();
    await expect(page.getByText("Updated context from the detail page.", { exact: true })).toBeVisible();
    await page.reload();
    await expect(page.getByText("Updated context from the detail page.", { exact: true })).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    expect((await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze()).violations).toEqual([]);
    await mkdir("docs/evidence/library-v2", { recursive: true });
    await page.screenshot({ path: `docs/evidence/library-v2/detail-${width}.png`, fullPage: true });
    await page.getByRole("link", { name: "Back to library" }).click();
    await expect(page.getByLabel("Search your library")).toHaveValue("useful");
    await page.getByRole("link", { name: "A useful find", exact: true }).focus();
    await page.keyboard.press("Enter");
    await expect(page.getByRole("heading", { name: "A useful find" })).toBeVisible();
    const other = await browser.newContext();
    const foreign = await other.newPage();
    await foreign.goto(`http://127.0.0.1:3100/items/${id}`);
    await expect(foreign).toHaveURL(/\/signin\?next=/);
    await foreign.getByLabel("Email address").fill(email);
    await foreign.getByLabel("Password", { exact: true }).fill(password);
    await foreign.getByRole("button", { name: "Sign in", exact: true }).click();
    await expect(foreign).toHaveURL(new RegExp(`/items/${id}$`));
    await expect(foreign.getByRole("heading", { name: "A useful find" })).toBeVisible();
    await other.request.post("http://127.0.0.1:3100/api/auth/signup", { headers, data: { email: `other-${randomUUID()}@example.test`, password, name: "Another user" } });
    await foreign.reload();
    await expect(foreign.getByRole("heading", { name: "Item not found", exact: true })).toBeVisible();
    await expect(foreign.getByText("Updated context from the detail page.")).toHaveCount(0);
    await other.close();
  });
}
